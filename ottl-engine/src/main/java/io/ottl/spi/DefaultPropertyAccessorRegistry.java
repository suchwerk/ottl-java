package io.ottl.spi;

import java.util.HashMap;
import java.util.Map;

/**
 * Default {@link PropertyAccessorRegistry}. Registration happens once (at build/startup) and the
 * registry is then read-only and safe to share across threads.
 */
public class DefaultPropertyAccessorRegistry implements PropertyAccessorRegistry {

    private final Map<Class<?>, PropertyAccessor> accessors = new HashMap<>();
    private final Map<Class<?>, TypeMetadata> metadata = new HashMap<>();
    private final Map<String, Class<?>> byName = new HashMap<>();

    /** Register a generated accessor for {@code type}. Called from generated bytecode in Quarkus. */
    public void register(Class<?> type, PropertyAccessor accessor) {
        accessors.put(type, accessor);
        metadata.put(type, TypeMetadata.parse(accessor.descriptor()));
        byName.put(type.getName(), type);
    }

    @Override
    public boolean contains(Class<?> type) {
        return accessors.containsKey(type);
    }

    @Override
    public java.util.Set<Class<?>> types() {
        return java.util.Set.copyOf(accessors.keySet());
    }

    @Override
    public PropertyAccessor accessor(Class<?> type) {
        return accessors.get(type);
    }

    @Override
    public TypeMetadata metadata(Class<?> type) {
        return metadata.get(type);
    }

    @Override
    public Class<?> typeByName(String fqn) {
        return byName.get(fqn);
    }
}
